// Builds everything the app needs from the licensed font shortlist in src/planner/fonts.json:
//  - src/planner/metrics.json: advance widths, so the layout engine measures text the same
//    way in the browser and on the server (title fitting, label truncation)
//  - public/fonts/*.woff2 + public/fonts/fonts.css: self-hosted web fonts (no Google request)
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import * as fontkit from 'fontkit';

const families = JSON.parse(readFileSync('src/planner/fonts.json', 'utf8'));
const RANGES = {
  latin: 'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD',
  'latin-ext': 'U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C0, U+2113, U+2C60-2C7F, U+A720-A7FF',
};

mkdirSync('public/fonts', { recursive: true });
const metrics = {};
let css = '/* Generated by scripts/build-metrics.mjs. All fonts are under the SIL Open Font License. */\n';

for (const [id, fam] of Object.entries(families)) {
  for (const [weight, file] of Object.entries(fam.files)) {
    const font = fontkit.openSync(`src/planner/fonts/${file}`);
    const adv = {};
    const put = (cp) => {
      if (font.hasGlyphForCodePoint(cp)) adv[String.fromCodePoint(cp)] = Math.round((font.glyphForCodePoint(cp).advanceWidth / font.unitsPerEm) * 1000);
    };
    for (let cp = 0x20; cp <= 0x24f; cp++) if (cp < 0x7f || cp >= 0xa0) put(cp);
    for (const ch of '–—‘’‚“”„…€') put(ch.codePointAt(0));
    metrics[`${id}-${weight}`] = { cap: Math.round((font.capHeight / font.unitsPerEm) * 1000), adv };

    for (const [subset, range] of Object.entries(RANGES)) {
      const name = `${fam.fontsource}-${subset}-${weight}-normal.woff2`;
      copyFileSync(`node_modules/@fontsource/${fam.fontsource}/files/${name}`, `public/fonts/${name}`);
      css += `@font-face { font-family: "${fam.css}"; font-style: normal; font-weight: ${weight}; font-display: swap; src: url("/fonts/${name}") format("woff2"); unicode-range: ${range}; }\n`;
    }
  }
}
writeFileSync('src/planner/metrics.json', JSON.stringify(metrics) + '\n');
writeFileSync('public/fonts/fonts.css', css);
console.log(Object.keys(metrics).join(' · '));
